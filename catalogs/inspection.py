def _replace_with_manual_criteria(metadata_key, note, criteria):
    metadata = _manual_metadata(note, criteria[0][0])
    metadata["criteria"] = []
    for name, measure_type, operands in criteria:
        criterion = _manual_metadata(note, name)["criteria"][0]
        criterion["measure_type"] = measure_type
        criterion["operands"] = operands
        metadata["criteria"].append(criterion)
    INSPECTION_MEASUREMENT_METADATA[metadata_key] = metadata


