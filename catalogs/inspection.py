def _original_criteria_parts(equipment_name, item_number):
    item = next(
        value
        for value in INSPECTION_DB[equipment_name]
        if value["no"] == item_number
    )
    parts = []
    current = ""
    for token in item["criteria"].split():
        if token[:1] in "①②③④⑤⑥⑦⑧⑨⑩":
            if current:
                parts.append(current.strip())
            current = token[1:]
        else:
            current = f"{current} {token}".strip()
    if current:
        parts.append(current.strip())
    return parts


